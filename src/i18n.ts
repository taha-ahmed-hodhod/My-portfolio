export type UiCopy = (typeof ui)[Locale];

export function buildResumeText(locale: Locale, d: {
  name: string; role: string; location: string; email: string; phone: string; intro: string;
  projects: { name: string; headline: string; summary: string }[];
  experiences: { date: string; company: string; role: string; body: string }[];
  skills: { title: string; items: string }[];
  education: { title: string; org: string; date: string; details: string }[];
}) {
  const t = ui[locale];
  return [
    d.name, d.role, d.location, d.email + ' · ' + d.phone, '',
    d.intro, '',
    t.selected,
    ...d.projects.map((p) => p.name + ' — ' + p.headline + '\n' + p.summary),
    '',
    t.experience,
    ...d.experiences.map((h) => h.date + ' | ' + h.company + ' | ' + h.role + '\n' + h.body),
    '',
    t.toolkit,
    ...d.skills.map((s) => s.title + ': ' + s.items),
    '',
    t.education,
    ...d.education.map((e) => e.title + ' — ' + e.org + ' (' + e.date + ') ' + e.details),
  ].join('\n\n');
}
